def _interp(table, m, case):
    """m (0.5~1.0) 에서 직선보간한 계수."""
    m = max(0.50, min(1.00, m))
    j = case - 1
    for i in range(len(M_RATIOS) - 1):
        hi, lo = M_RATIOS[i], M_RATIOS[i + 1]
        if lo <= m <= hi:
            r = (hi - m) / (hi - lo)
            return table[i][j] + (table[i + 1][j] - table[i][j]) * r
    return table[-1][j]


def coefficients(m, case):
    """{'ca_neg','cb_neg','ca_dl','cb_dl','ca_ll','cb_ll','wa','wb'}"""
    wa = _interp(WA, m, case)
    return {
        "ca_neg": _interp(CA_NEG, m, case), "cb_neg": _interp(CB_NEG, m, case),
        "ca_dl": _interp(CA_DL, m, case),   "cb_dl": _interp(CB_DL, m, case),
        "ca_ll": _interp(CA_LL, m, case),   "cb_ll": _interp(CB_LL, m, case),
        "wa": wa, "wb": 1.0 - wa,
    }
